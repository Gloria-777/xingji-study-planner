const DAY_NAMES = ['', '周一', '周二', '周三', '周四', '周五', '周六', '周日'];
// Intl.DateTimeFormat 的构造不便宜，而且每条对话都要算一次「现在是几点」。
// 选项是固定的，所以建一次共用；formatToParts 每次照样拿当下时间，读数不变。
const CN_FMT = new Intl.DateTimeFormat('sv-SE', {
  timeZone: 'Asia/Shanghai',
  year: 'numeric', month: '2-digit', day: '2-digit',
  hour: '2-digit', minute: '2-digit', hour12: false,
});

export function nowCN() {
  const parts = CN_FMT.formatToParts(new Date());
  const get = (t) => parts.find((p) => p.type === t).value;
  const dateStr = `${get('year')}-${get('month')}-${get('day')}`;
  const hour = get('hour') === '24' ? '00' : get('hour');
  const nowMin = Number(hour) * 60 + Number(get('minute'));
  const jsDay = new Date(`${dateStr}T12:00:00+08:00`).getDay();
  return { dateStr, day: ((jsDay + 6) % 7) + 1, nowMin, hour, minute: get('minute') };
}

export function nowContext() {
  const n = nowCN();
  return `当前时间：${n.dateStr} ${DAY_NAMES[n.day]} ${n.hour}:${n.minute}`;
}

export function scheduleContext(courses, tasks) {
  const courseLines = courses.length
    ? courses
        .slice()
        .sort((a, b) => a.day - b.day || a.start_time.localeCompare(b.start_time))
        .map((c) => `[id=${c.id}] ${DAY_NAMES[c.day]} ${c.start_time}-${c.end_time} ${c.name}${c.location ? ` @${c.location}` : ''}${c.teacher ? `（${c.teacher}）` : ''}`)
    : ['（暂无课表）'];
  const pending = tasks.filter((t) => t.status !== 'done');
  const taskLines = pending.length
    ? pending
        .slice()
        .sort((a, b) => (a.due_at || '').localeCompare(b.due_at || ''))
        .slice(0, 30)
        .map((t) => `[id=${t.id}] ${t.title}${t.subject ? `（${t.subject}）` : ''}${t.due_at ? ` 截止 ${t.due_at.replace('T', ' ')}` : ''}`)
    : ['（暂无学习任务）'];
  return `## 学生课表\n${courseLines.join('\n')}\n\n## 待办学习任务\n${taskLines.join('\n')}`;
}

